/*
 * 携帯型アイテムを持てるもの(プレイヤーなど)が実装するインターフェース
 * アイテムスロットの実体はこのインターフェースを実装する側が持つ
 *
 * 制作者：　KR
 */

// ========================================
/*
 * メモ
 * プレイヤー側は、このインターフェースを実装するだけで携帯型アイテムを拾えるようになる
 *   public class CS_Player : NetworkBehaviour, ICarriableItemHolder
 *   {
 *       public bool TryStoreItem(CSO_ItemDataCarriable item) { ... }
 *   }
 * ・スロットが空いていれば格納してtrueを返す。埋まっていればfalseを返す(アイテムはフィールドに残る)
 * ・格納したアイテムの発動(CSO_ItemDataCarriable.Activateを呼ぶ)は、使用ボタンなど
 *   任意のタイミングでプレイヤー側から行う想定(このインターフェースの責務外)
 * ・誰が何を持っているかを他クライアントに同期する方法(NetworkVariable化など)も
 *   プレイヤー側の実装に依存するため、ここでは規定しない
 * ※ プレイヤーのアイテムスロットは未実装のため、現状はICarriableItemHolder未実装のままであり
 *    CSO_ItemDataCarriableは対象が見つからず警告ログを出すだけで終わる
 */
// ========================================

public interface ICarriableItemHolder
{
    // 携帯型アイテムをスロットに格納する。格納できたらtrueを返す
    bool TryStoreItem(CSO_ItemDataCarriable item);
}
