 * エフェクトを指定するためのID
 * CSO_EffectDataBase(DB_EffectDataBase)で、IDごとに出すPrefabを決める
 *
 * 制作者：　吉田京志郎
 */

// ========================================
/*
 * メモ
 * ・SEのID(CSE_SeId)と同じく、数値の帯でカテゴリを分ける
 *   プレイヤー: 200番台 / 警察: 300番台 / 悪人: 400番台 / アイテム: 500番台
 * ・DB_EffectDataBaseには数値で保存されるので、途中に追加する時は既存の値を変えないこと
 *   (並びの最後に足すか、値を明示して追加する)
 */
// ========================================

public enum CSE_EffectId
{
    None = 0,

    // =========================================================
    // プレイヤー：200番台
    // =========================================================
    PlayerAttack1 = 200,    // 通常攻撃1段目の殴り(こぶしの軌跡)
    PlayerAttack2,          // 通常攻撃2段目の殴り
    PlayerAttack3,          // 通常攻撃3段目の殴り
    PlayerAttack4,          // 通常攻撃4段目の殴り
    PlayerAttack5,          // 通常攻撃5段目の殴り
    PlayerSpecialStart,     // 必殺技の発動
    PlayerSpecialHit,       // 必殺技の判定が出た瞬間
    PlayerDamage,           // プレイヤーが攻撃を受けた
    PlayerAttackImpact,     // 通常攻撃1〜4段目の判定が出た瞬間(殴った所の衝撃)
    PlayerAttackFinishImpact, // 通常攻撃の最後の段の判定が出た瞬間

    // =========================================================
    // 警察：300番台
    // =========================================================
    PoliceAttack = 300,     // 警察の攻撃判定が出た瞬間

    // =========================================================
    // 悪人：400番台
    // =========================================================
    VillainAttack = 400,    // 悪人の攻撃判定が出た瞬間
    VillainDamage,          // 悪人が攻撃を受けた
}
