/*
 * 犯罪実行役に設定する犯罪モーション(巡回パターンの犯罪実行役の設定)
 * Autoなら、担当のエリア(CS_CrimeArea.crimeMotion)のモーションを使う
 *
 * 制作者：　中出峻輔
 */

public enum CSE_VillainCrimeMotion : byte
{
    Auto,     // エリアに合わせる(生活区域: 蹴る / インフラ区域: 運ぶ / エネルギー区域: いじる)
    Kick,     // 蹴る(食料ジェネレーター・自販機を蹴って壊そうとする)
    Carry,    // 運ぶ(未配達の貨物を盗んで、車に詰め込む。貨物の位置と車の位置を往復する)
    Tamper,   // いじる(制御盤をいじって壊そうとする)
}
