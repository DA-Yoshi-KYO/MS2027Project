/// <summary>
/// リザルトの称号の種類
/// ・称号は条件を満たしたものを全部出す(複数)。決め方は CS_ResultTitleDecider
/// ・数値(=1、=2…)は変えない。DB_ResultSpriteTable に割り当てた画像が、数値で保存されているため
///   (称号を増やす時は、いちばん下に新しい数値で足す)
/// </summary>
public enum CSE_ResultTitle
{
    /// <summary>称号なし(判定では出ない。念のための値)</summary>
    None = 0,

    /// <summary>ワンショットワンダウン : 奇襲の成功回数が規定回数以上</summary>
    OneShotOneDown = 1,

    /// <summary>ステルスアクションの名手 : ステルスアクション(SA)の使用回数が規定回数以上</summary>
    StealthMaster = 2,

    /// <summary>警察いらずの暗躍者 : 警察に見つかった数が規定回数以下</summary>
    PoliceFree = 3,

    /// <summary>稀代のダークヒーロー : 上の3つをすべて満たした</summary>
    DarkHero = 4,
}
