using UnityEngine;

// ========================================
/*
 * メモ
 * ・ソロでは要らない物(ランキングUIなど)に付けると、ソロの時だけ最初に無効にする
 * ・CS_GameModeSwitcher はフィールドのプレハブ(Field)の中にあり、シーンのUIを参照できないので、
 *   UI側はこれを付けて自分で消す
 * ・他の物のAwakeより先に無効にするため、実行順を早めている(CS_GameModeSwitcherと同じ)
 */
// ========================================
[DefaultExecutionOrder(-1000)]
public class CS_HideInSolo : MonoBehaviour
{
    void Awake()
    {
        if (CS_GameModeStore.isSolo) gameObject.SetActive(false);
    }
}
