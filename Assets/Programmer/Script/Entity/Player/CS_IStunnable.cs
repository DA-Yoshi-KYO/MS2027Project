/*
 * スタン(一定時間、行動を止める)できるものが実装するインターフェース
 * プレイヤーのパリー(CS_PlayerParry)が成功した時、攻撃してきた相手がこれを持っていればStunを呼ぶ
 *
 * 制作者：　秋野翔太
 */

// ========================================
/*
 * メモ
 * ・仕様書「プレイヤー」のブリンク: 「この反撃を決めると警察すらスタンさせることができ、逃げることができます」
 * ・実装してほしいもの(警察の担当者へ依頼): CS_PoliceBrainなど、警察の行動を止められるコンポーネントで実装する
 *   Stun(duration) を呼ばれたら、duration秒の間
 *     ・移動を止める
 *     ・今の攻撃(溜め)を中断し、新しい攻撃も始めない
 *   その後、元の行動に戻る
 * ・Stunはサーバー(またはオフライン)で呼ばれる(パリーの判定はサーバーで行うため)
 * ・まだ実装しているものが無い間は、パリーで警察をスタンさせることはできない(反撃の演出・無敵は入る)
 */
// ========================================

public interface IStunnable
{
    // duration秒の間、行動を止める
    void Stun(float duration);
}
