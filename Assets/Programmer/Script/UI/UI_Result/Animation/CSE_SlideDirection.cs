/// <summary>
/// スライドで入ってくる向き(どの方向の画面の外から入ってくるか)
/// </summary>
public enum CSE_SlideDirection
{
    /// <summary>画面の上の外から、下へ向かって入る</summary>
    FromTop,

    /// <summary>画面の左の外から、右へ向かって入る</summary>
    FromLeft,

    /// <summary>画面の右の外から、左へ向かって入る</summary>
    FromRight,

    /// <summary>画面の下の外から、上へ向かって入る</summary>
    FromBottom,
}
