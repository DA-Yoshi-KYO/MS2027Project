/// <summary>
/// 巡回ドローンの状態を表す列挙型(見た目を全員の画面で合わせるために、全クライアントへ同期する)
/// </summary>
public enum CSE_SecurityDroneState
{
    /// <summary>
    /// 巡回中(青)
    /// </summary>
    Patrol,

    /// <summary>
    /// プレイヤーを見つけている間(目が青と赤で点滅)
    /// </summary>
    Detected,

    /// <summary>
    /// プレイヤーを見失ったあとも、しばらく追ってくる(青)
    /// </summary>
    Chase,

    /// <summary>
    /// 背中から攻撃されて止まっている(目が消える)
    /// </summary>
    Stunned,

    /// <summary>
    /// 制圧モード: プレイヤーを追いながら、テーザーを溜めている(目が点滅)
    /// </summary>
    TaserCharge,

    /// <summary>
    /// 制圧モード: テーザーを撃つ向きを決めて、赤い線で知らせている(避けられる)
    /// </summary>
    TaserAim,

    /// <summary>
    /// 制圧モード: テーザーが当たったプレイヤーへ、近づいている
    /// </summary>
    KillApproach,

    /// <summary>
    /// 制圧モード: 即死攻撃を溜めている(地面に範囲の赤い円が出る。範囲から出られなければ即死)
    /// </summary>
    KillCharge,

    /// <summary>
    /// 制圧モード: 攻撃のあとの隙(動かない。プレイヤーは逃げられる)
    /// </summary>
    Recovery,
}
