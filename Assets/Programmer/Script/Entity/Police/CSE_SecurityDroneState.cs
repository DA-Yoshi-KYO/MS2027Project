/// <summary>
/// 巡回ドローンの状態を表す列挙型(見た目を全員の画面で合わせるために、全クライアントへ同期する)
/// </summary>
public enum CSE_SecurityDroneState
{
    /// <summary>
    /// 巡回中(青)
    /// </summary>
    Patrol,

    /// <summary>
    /// プレイヤーを見つけている間(目が青と赤で点滅)
    /// </summary>
    Detected,

    /// <summary>
    /// プレイヤーを見失ったあとも、しばらく追ってくる(青)
    /// </summary>
    Chase,

    /// <summary>
    /// 背中から攻撃されて止まっている(目が消える)
    /// </summary>
    Stunned,
}
